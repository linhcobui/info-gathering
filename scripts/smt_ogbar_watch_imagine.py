"""OGBar-SMT stage 1: ground truth | open-loop from the start | watch (posterior) to a cut, then imagine.

The readout R (stage 2) is not built, so frames are generated by the stage-1 future decoder: from the belief z
at the start point and the real frame there, it predicts x_{t+1}, then reads its own prediction back in
(autoregressive, real recorded actions). Its sequence begins at the start point, so anything from before
it -- e.g. an earlier probe's tilt -- can only reach the prediction through z.

  open-loop from start   z = teacher on the window at t = 0 (eval_warmup = 1); decoder rolls out from step 0
  watch, then imagine    z_0 as above; z_{t+1} = sample of Q(z_t, x_t, a_t, real x_{t+1}) up to the cut
                         (shown: the decoder's 1-step prediction from the chained z_t); from the cut the decoder
                         rolls out from the chained z_cut. The decoder reads at most `future` (200) steps.
Tokens are rendered with the DINO-WM pixel decoder (trained on real DINOv2 tokens only).

    pixi run python scripts/smt_ogbar_watch_imagine.py --ckpt logdir/world_model/smt_ogbar/v3_400_gaussian/checkpoints/wm_latest.pt
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import imageio.v2 as imageio  # noqa: E402
import numpy as np  # noqa: E402
import torch  # noqa: E402
import zarr  # noqa: E402
from omegaconf import OmegaConf  # noqa: E402

from dino_wm_videos import decode_all  # noqa: E402
from dino_wm_watch_imagine import img_tilt, panel  # noqa: E402
from info_gathering.ogbar_smt_data import OgbarSmtAnchors  # noqa: E402
from train_dino_wm import build_model  # noqa: E402
from world_model.models.smt_ogbar import SmtOgbar  # noqa: E402
from world_model.utils.checkpoint import CheckpointManager  # noqa: E402

LIFT = 1   # play.PROBE_STAGES index of 'lift'
AMP = dict(device_type="cuda", dtype=torch.bfloat16)


@torch.no_grad()
def decoder_rollout(m, z, x0, actions):
    """z (K, d), x0 (256, 384) the real frame at the start, actions (H, 25) a_start .. -> predicted x (H, 256, 384)."""
    toks, preds = [], []
    x = x0
    for k in range(len(actions)):
        with torch.autocast(**AMP):
            toks.append(m.dec_step_in(torch.cat([m.pool(x[None]), actions[k:k + 1].to(x.dtype)], -1)))
            out = m.decoder(torch.cat([z[None], torch.stack(toks, 1)], 1))[:, m.K + k]
            x = m.head(out)[0]
        preds.append(x.float())
    return torch.stack(preds)


@torch.no_grad()
def one_step_preds(m, zs, patch, action):
    """Decoder's prediction of x_{t+1} from z_t and (x_t, a_t), for every t: (T-1, 256, 384)."""
    out = []
    for t in range(len(zs)):
        with torch.autocast(**AMP):
            tok = m.dec_step_in(torch.cat([m.pool(patch[t][None]), action[t:t + 1].to(patch.dtype)], -1))
            out.append(m.head(m.decoder(torch.cat([zs[t][None], tok[:, None]], 1))[:, m.K])[0].float())
    return torch.stack(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--pixel-decoder", default="logdir/world_model/dino_wm_ogbar/v3_400_proprio/checkpoints/wm_latest.pt")
    ap.add_argument("--zarr", default="data/ogbar_v3_eval5.zarr")
    ap.add_argument("--episode", type=int, default=3)
    ap.add_argument("--cut-probe", type=int, default=2)
    ap.add_argument("--fps", type=int, default=8)
    ap.add_argument("--device", default="cuda:1")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    torch.manual_seed(args.seed)
    dev = torch.device(args.device)

    st = CheckpointManager.load(args.ckpt)
    m = SmtOgbar(action_dim=25, **st["config"]["model"]).to(dev).eval()
    m.load_state_dict(st["model"])
    pst = CheckpointManager.load(args.pixel_decoder)
    pix = build_model(OmegaConf.create(pst["config"]), pst["stats"], 25, 19).to(dev).eval()
    pix.load_state_dict(pst["model"])

    data = OgbarSmtAnchors(ROOT / (args.zarr.removesuffix(".zarr") + "_dinov2"), ROOT / args.zarr, 5)
    z = zarr.open_group(str(ROOT / args.zarr), "r")
    e = args.episode
    s0, e0 = int(data.starts[e]), int(data.ends[e])
    ps = z["probe_stage"][s0:e0]
    lift_starts = [t for t in range(len(ps)) if ps[t] == LIFT and (t == 0 or ps[t - 1] != LIFT)]
    cut = -(-lift_starts[args.cut_probe - 1] // 5)
    c_cm = float(z["episode/com_offset_c"][e]) * 100
    patch, action = data.load(e, 0)
    patch, action = patch.to(dev).to(torch.bfloat16), m.norm_action(action.to(dev))   # model's action scaling
    real = z["rgb"][s0:e0][::5][:len(patch)]
    T, H = len(patch), m.cfg["future"]

    with torch.no_grad(), torch.autocast(**AMP):
        z0 = m.teacher_windows(m.pool(patch[None]), action[None], torch.zeros(1, 1, dtype=torch.long, device=dev))[0, 0]
        zs = [z0]
        for t in range(T - 1):                                   # posterior chain over every real step
            mu, ls = m.posterior(zs[-1][None], patch[t][None], action[t][None], patch[t + 1][None])
            zs.append(m.sample(mu, ls)[0])
    zs = torch.stack(zs).to(torch.bfloat16)
    ol = decoder_rollout(m, z0, patch[0], action[:min(T - 1, H)])            # x_1 .. x_200
    one = one_step_preds(m, zs[:cut], patch, action)                         # x_1 .. x_cut
    imag = decoder_rollout(m, zs[cut], patch[cut], action[cut:min(T - 1, cut + H)])   # x_cut+1 ..
    dec = lambda x: decode_all(pix, x.to(dev))
    ol_img, one_img, im_img = dec(ol), dec(one), dec(imag)

    blank = np.zeros_like(real[0])
    frames = []
    for t in range(T):
        gt = panel(real[t], f"ground truth  ep {e}  c {c_cm:+.1f} cm", f"step {t}  ")
        a = panel(real[t], "open-loop from start", "real start  ") if t == 0 else \
            panel(ol_img[t - 1], "open-loop from start", f"+{t}  ") if t - 1 < len(ol_img) else \
            panel(blank, "open-loop from start", "past the decoder's 200 steps")
        if t == 0:
            b = panel(real[t], "watch, then imagine", "real start  ")
        elif t <= cut:
            b = panel(one_img[t - 1], "WATCHING (posterior chain)", "1-step pred  ")
        elif t - cut - 1 < len(im_img):
            b = panel(im_img[t - cut - 1], f"IMAGINING from step {cut}", f"+{t - cut}  ")
        else:
            b = panel(blank, f"IMAGINING from step {cut}", "past the decoder's 200 steps")
        frames.append(np.concatenate([gt, a, b], axis=1))
    out = Path(args.ckpt).parents[1] / "videos"
    out.mkdir(exist_ok=True)
    out = out / f"{Path(args.zarr).stem}_ep{e:03d}_watch{args.cut_probe}_imagine_step{st['step']}.mp4"
    imageio.mimwrite(out, frames, fps=args.fps, macro_block_size=8)
    holds = [t for t in range(len(ps)) if ps[t] == 2 and (t == 0 or ps[t - 1] != 2)]
    mids = [min((t + 20) // 5, T - 1) for t in holds]
    imageio.imwrite(out.with_suffix(".png"), np.concatenate([frames[i] for i in mids], 0))
    print(f"{out} ({T} steps, cut at step {cut}; checkpoint step {st['step']})")
    tilt = lambda im: img_tilt(im[27:])
    for p, i in enumerate(mids):
        o = tilt(ol_img[i - 1]) if 0 < i <= len(ol_img) else np.nan
        w = tilt(one_img[i - 1]) if 0 < i <= cut else tilt(im_img[i - cut - 1]) if i - cut - 1 < len(im_img) else np.nan
        print(f"  probe {p + 1} (step {i}): GT {tilt(real[i]):+.0f}  open-loop {o:+.0f}  "
              f"{'watch 1-step' if i <= cut else 'imagine'} {w:+.0f}  (privileged {np.degrees(z['bar_tilt'][s0 + i * 5]):+.0f})")


if __name__ == "__main__":
    main()
